window.getCabmyNews = function(count) {
  const sorted = [...window.CABMY_NEWS].sort((a, b) => (b.dateSort || '').localeCompare(a.dateSort || ''));
  return typeof count === 'number' ? sorted.slice(0, count) : sorted;
};

window.getMediaItems = function(article) {
  if (!article) return [];
  const items = [];
  const pushValue = (value) => {
    if (Array.isArray(value)) {
      value.forEach(pushValue);
      return;
    }
    if (typeof value === 'string' && value.trim()) {
      const trimmed = value.trim();
      try {
        const parsed = JSON.parse(trimmed);
        if (Array.isArray(parsed)) {
          parsed.forEach(pushValue);
          return;
        }
      } catch (err) {
        // not JSON, keep as normal string
      }
      items.push(trimmed);
    }
  };

  pushValue(article.mediaUrls);
  pushValue(article.photoUrls);
  pushValue(article.images);
  pushValue(article.photos);
  pushValue(article.mediaUrl);

  if (!items.length && article.mediaFilename) {
    const prefix = window.CABMY_NEWS_MEDIA_PATH || '';
    items.push(prefix + article.mediaFilename);
  }

  return items.filter((url, index) => items.indexOf(url) === index);
};

window.getMediaUrl = function(article) {
  if (!article) return '';
  const mediaItems = window.getMediaItems ? window.getMediaItems(article) : [];
  return mediaItems[0] || '';
};

window.escapeNewsHtml = function(text) {
  return String(text || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
};

window.renderNewsCardHtml = function(article, options = {}) {
  const label = options.useCategoryLabel ? article.categoryFr || article.cat : article.cat;
  const badgeColor = article.cat === 'resultats' ? 'var(--gold-light);color:#7a5c00' : article.cat === 'spiritualite' ? 'var(--blue-light);color:var(--blue)' : article.cat === 'soir' ? 'background:rgba(255,255,255,.1);color:rgba(255,255,255,.8)' : 'background:var(--gold-light);color:#7a5c00';
  const link = options.home ? (article.link || 'src/pages/actualites.html') : '#';
  const clickHandler = options.home ? '' : 'onclick="openArticle(this); return false;"';
  const readTextFr = options.home ? 'Lire →' : 'Lire l\'article →';
  const readTextEn = options.home ? 'Read →' : 'Read article →';
  const mediaUrl = window.getMediaUrl(article);
  const mediaHtml = mediaUrl ? `<img src="${escapeNewsHtml(mediaUrl)}" alt="${escapeNewsHtml(article.titleFr || article.titleEn || 'Actualité')}" />` : escapeNewsHtml(article.emoji || '📰');
  const visibleClass = options.home ? 'visible' : 'fade-up';
  const delayClass = options.home ? '' : 'fade-up-d1';

  return `
    <div class="news-card card-hover ${visibleClass} ${delayClass}">
      <div class="news-card-thumb">${mediaHtml}</div>
      <div class="news-card-body">
        <span class="news-badge" style="${badgeColor}" data-fr="${escapeNewsHtml(article.categoryFr || label)}" data-en="${escapeNewsHtml(article.categoryEn || label)}">${escapeNewsHtml(article.categoryFr || label)}</span>
        <h4 class="news-card-title" data-fr="${escapeNewsHtml(article.titleFr)}" data-en="${escapeNewsHtml(article.titleEn)}">${escapeNewsHtml(article.titleFr)}</h4>
        <p class="news-card-desc" data-fr="${escapeNewsHtml(article.resumeFr)}" data-en="${escapeNewsHtml(article.resumeEn)}">${escapeNewsHtml(article.resumeFr)}</p>
        <div class="news-card-footer"><span>${escapeNewsHtml(article.date)}</span><a href="${link}" class="news-card-read" ${clickHandler} data-fr="${escapeNewsHtml(readTextFr)}" data-en="${escapeNewsHtml(readTextEn)}">${escapeNewsHtml(readTextFr)}</a></div>
      </div>
    </div>
  `;
};

window.renderHomepageNews = function(count) {
  const container = document.querySelector('.news-section .news-grid');
  if (!container || !window.CABMY_NEWS) return;

  const newsCardsHtml = window.getCabmyNews(count).map(article => window.renderNewsCardHtml(article, { home: true, useCategoryLabel: true }));
  container.classList.remove('home-news-slider');
  container.innerHTML = newsCardsHtml.join('');
};

window.renderArticlesGrid = function(articles) {
  const grid = document.getElementById('articles-grid');
  if (!grid || !Array.isArray(articles)) return;
  grid.innerHTML = articles.map(article => {
    const mediaBlock = window.renderArticleMediaBlock ? window.renderArticleMediaBlock(article) : `<div class="news-img" style="background:linear-gradient(135deg,var(--blue-light),#d0ddf5)">${escapeNewsHtml(article.emoji || '📰')}</div>`;
    const category = escapeNewsHtml(article.categoryFr || article.cat || 'Actualité');
    return `
      <div class="article-card show card-hover rounded-2xl overflow-hidden border border-gray-100 shadow-sm" data-cat="${escapeNewsHtml(article.cat)}">
        ${mediaBlock}
        <div class="p-6">
          <span class="text-xs font-semibold px-2 py-1 rounded" style="background:var(--blue-light);color:var(--blue)">${category}</span>
          <h3 class="font-bold text-lg mt-3 mb-2" style="color:var(--blue)" data-fr="${escapeNewsHtml(article.titleFr)}" data-en="${escapeNewsHtml(article.titleEn)}">${escapeNewsHtml(article.titleFr)}</h3>
          <p class="text-gray-500 text-sm mb-4 leading-relaxed" data-fr="${escapeNewsHtml(article.resumeFr)}" data-en="${escapeNewsHtml(article.resumeEn)}">${escapeNewsHtml(article.resumeFr)}</p>
          <div class="flex justify-between items-center text-xs text-gray-400">
            <span>${escapeNewsHtml(article.date)}</span>
            <a href="#" onclick="openArticle(this); return false;" class="font-semibold" style="color:var(--gold)" data-fr="Lire l'article →" data-en="Read article →">Lire l'article →</a>
          </div>
        </div>
      </div>
    `;
  }).join('');
};

window.renderArticleMediaBlock = function(article) {
  const mediaUrl = window.getMediaUrl(article);
  if (article.mediaType === 'photo' && mediaUrl) {
    return `<img src="${escapeNewsHtml(mediaUrl)}" alt="${escapeNewsHtml(article.mediaAlt || article.titleFr || article.titleEn)}" class="news-img object-cover" loading="lazy" />`;
  }
  if (article.mediaType === 'video' && mediaUrl) {
    return `<video controls class="news-img" preload="metadata"><source src="${escapeNewsHtml(mediaUrl)}" type="video/mp4">Votre navigateur ne supporte pas la vidéo.</video>`;
  }
  return `<div class="news-img" style="background:linear-gradient(135deg,var(--blue-light),#d0ddf5)">${escapeNewsHtml(article.emoji || '📰')}</div>`;
};
